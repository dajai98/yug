import hashlib
import json
import pytest
from training import dataset_rights_scope as r
from training.production_corpus import atomic_json, canonical, file_digest
from training.production_spec import seal, SpecificationError

CARD='''---
license: mit
source_datasets: [original]
configs:
- config_name: main
  data_files:
  - split: train
    path: main/train-*
---
#### Initial Data Collection and Normalization
The dataset creators commissioned original questions and answers. Workers independently checked every problem and corrected errors before publishing this collection.
### Licensing Information
The sample dataset is licensed under the [MIT License](https://opensource.org/licenses/MIT).
### Citation Information
Creator citation.
'''

def source():return dict(source_id='sample',dataset_id='org/sample',revision='a'*40,license_id='MIT',locator='https://huggingface.co/datasets/org/sample')

def document():return seal(dict(policy='dataset-document-clearance-v1',document_identity='doc',source_id='sample',revision='a'*40,path='record',sha256='hash',
    status='REVIEW',reason='No row grant',provenance=dict(dataset_id='org/sample',revision='a'*40,payload_path='main/train-0.parquet',upstream_split='train')))

def test_materializes_dataset_scope_without_row_licenses():
    scope=r.scope_from_card(CARD,source(),'card')
    assert scope['status']=='COVERED'
    out=r.resolve(document(),scope)
    assert out['status']=='CLEAR' and out['license_id']=='MIT' and not out['training_allowed']
    assert out==r.resolve(document(),scope)


@pytest.mark.parametrize('claim',[
    'The records are synthetic.',
    'Text was generated by an upstream model.',
    'Queries were extracted from https://huggingface.co/datasets/org/upstream.',
    'The collection was derived from scraped seed data.'])
def test_derivative_claims_override_original_label(claim):
    scope=r.assess_provenance(CARD+'\n'+claim,source(),'card')
    assert scope['status']=='REVIEW'
    assert r.resolve(document(),scope)['status']=='REVIEW'
    a=scope['provenance_assessment']
    assert a['missing_evidence'] and not a['upstream_rights_verified']
    assert not a['generated_record_coverage_verified']
    assert scope==r.assess_provenance(CARD+'\n'+claim,source(),'card')


def test_provenance_assessment_preserves_supported_positive_scope():
    scope=r.assess_provenance(CARD,source(),'card')
    assert r.resolve(document(),scope)['status']=='CLEAR'
    with pytest.raises(SpecificationError):r.resolve(document(),seal(dict(scope,revision='b'*40)))


def test_incompatible_declared_license_excludes_without_inventing_rights():
    s=dict(source(),license_id='CC-BY-NC-4.0')
    scope=r.assess_provenance(CARD.replace('license: mit','license: cc-by-nc-4.0')+'\nSynthetic records.',s,'card')
    assert r.resolve(document(),scope)['status']=='EXCLUDE'
    # Conflicting evidence is uncertainty, not a proven incompatible declaration.
    assert r.assess_provenance(CARD+'\nSynthetic records.',s,'card')['status']=='REVIEW'
    s=dict(source(),license_id='unknown')
    assert r.assess_provenance(CARD.replace('license: mit','license: unknown'),s,'card')['status']=='REVIEW'

@pytest.mark.parametrize('old,new',[
    ('[original]','[upstream]'),('license: mit','license: other'),
    ('dataset is licensed','code is licensed'),('https://opensource.org/licenses/MIT','https://example.com/license'),
    ('main/train-*','../*'),('license: mit','license: mit\nlicense: gpl'),
    ('Creator citation.','Creator citation. Third-party records have separate terms.'),
    ('before publishing this collection.','before publishing this collection. Other data was scraped.'),
    ('MIT).','MIT). Except for some records.')])
def test_ambiguity_remains_review(old,new):
    assert r.scope_from_card(CARD.replace(old,new),source(),'card')['status']=='REVIEW'

def test_excluded_and_ambiguous_scope():
    scope=r.scope_from_card(CARD,source(),'card');doc=document()
    assert r.resolve(seal(dict(doc,status='EXCLUDE',reason='heldout')),scope)['status']=='EXCLUDE'
    other=seal(dict(doc,provenance=dict(doc['provenance'],payload_path='test/file.parquet')))
    assert r.resolve(other,scope)['status']=='EXCLUDE'
    assert r.resolve(doc,seal(dict(scope,routes=scope['routes']*2)))['status']=='REVIEW'
    with pytest.raises(SpecificationError):r.resolve(doc,seal(dict(scope,revision='b'*40)))

def test_build_resume_and_corruption(tmp_path):
    docs=tmp_path/'docs';cards=tmp_path/'cards';cache=tmp_path/'cache';out=tmp_path/'out'
    for p in (docs,cards,cache/'sample/files'):p.mkdir(parents=True)
    s=source();cat=tmp_path/'catalog.json';atomic_json(cat,seal(dict(sources=[s])))
    card=cards/'sample.md';card.write_bytes(CARD.encode())
    blob=hashlib.sha1(f'blob {len(card.read_bytes())}\0'.encode()+card.read_bytes()).hexdigest()
    atomic_json(cards/'sample.json',seal(dict(dataset_id=s['dataset_id'],revision=s['revision'],path='cards/sample.md',sha256=file_digest(card),git_blob=blob,
        url=s['locator']+'/raw/'+s['revision']+'/README.md',tree_url='https://huggingface.co/api/datasets/org/sample/tree/'+s['revision'],
        tree_entry=dict(path='README.md',type='file',size=card.stat().st_size,oid=blob))))
    raw=cache/'sample/payload.parquet';raw.write_bytes(b'fixture-payload')
    payload=cache/'sample/files/row.json';payload.write_bytes(b'{"value":1}')
    doc=document();doc=seal(dict(doc,sha256=file_digest(payload),provenance=dict(doc['provenance'],payload_sha256=file_digest(raw))))
    inv=cache/'sample/inventory.jsonl';inv.write_bytes(canonical(dict(path=doc['path'],sha256=doc['sha256'],local_blob='files/row.json',provenance=doc['provenance']))+b'\n')
    atomic_json(cache/'sample/complete.json',seal(dict(inventory_sha256=file_digest(inv))))
    atomic_json(docs/'request.json',seal(dict(policy='dataset-document-clearance-v1',inputs={'catalog.json':file_digest(cat)})))
    (docs/'decisions.jsonl').write_bytes(canonical(doc)+b'\n')
    atomic_json(docs/'complete.json',seal(dict(request_identity=json.loads((docs/'request.json').read_bytes())['identity'],decisions_sha256=file_digest(docs/'decisions.jsonl'),documents=1)))
    args=dict(documents=docs,catalog=cat,cards=cards,cache=cache,output=out,root=tmp_path)
    first=r.build(**args);assert first['counts']['CLEAR']==1
    assert r.build(**args,resume=True)==first
    card.write_bytes(b'changed')
    with pytest.raises(SpecificationError):r.build(**args,resume=True)
