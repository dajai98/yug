"""Apply a verified original-dataset card scope to exact document proofs.

CLEAR is evidence coverage, not legal certainty or a production admission grant.
Unsupported declarations/derivative provenance remain REVIEW.
"""
import argparse
from collections import Counter
import fnmatch
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import yaml

from training.production_corpus import atomic_json, atomic_replace, canonical, file_digest
from training.production_spec import need, seal, verify_seal, local_path
from training.source_prepare import ROOT, LICENSES
from training.token_shards import _writer_lock
from training.dataset_payload import payload_digest
from training.conditional_license import CONDITIONAL

VERSION='original-dataset-card-scope-v1'


class UniqueLoader(yaml.SafeLoader):
    pass


def unique_mapping(loader,node,deep=False):
    result={}
    for key,value in node.value:
        k=loader.construct_object(key,deep=deep)
        need(isinstance(k,str) and k not in result,'Duplicate/non-string card key')
        result[k]=loader.construct_object(value,deep=deep)
    return result


UniqueLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG,unique_mapping)


def scope_from_card(text,source,receipt_identity):
    """Narrow generic evidence profile, independent of dataset names/row IDs."""
    result=dict(dataset_id=source['dataset_id'],revision=source['revision'],license_id=source['license_id'],
                card_identity=receipt_identity,status='REVIEW',reason='unsupported/ambiguous dataset license scope',routes=[])
    if source['license_id'] in CONDITIONAL:
        return seal(dict(result,reason='CONDITIONAL license requires explicit source-specific approval; card cannot clear records'))
    parts=text.split('---',2)
    if len(parts)!=3 or parts[0].strip():return seal(result)
    try:
        data=yaml.load(parts[1],Loader=UniqueLoader)
    except (yaml.YAMLError,ValueError):return seal(result)
    if not isinstance(data,dict):return seal(result)
    if re.search(r'not licensed|non.commercial|license exception|third.party|all rights reserved|prohibit|excluded from',parts[2],re.I):
        return seal(dict(result,reason='additional rights/provenance qualification requires review'))
    declared=data.get('license');declared=declared[0] if isinstance(declared,list) and len(declared)==1 else declared
    if not isinstance(declared,str) or declared.casefold()!=source['license_id'].casefold():return seal(result)
    if source['license_id'] not in LICENSES:return seal(dict(result,status='EXCLUDE',reason='license outside existing allowlist'))
    # Original provenance must be explicit. Never infer coverage of derived,
    # aggregated, synthetic or third-party records from a downstream MIT label.
    if data.get('source_datasets')!=['original']:
        return seal(dict(result,reason='original dataset provenance not established; upstream scope unresolved'))
    section=re.search(r'^### Licensing Information\s*\n(.*?)(?=^#{1,3} |\Z)',parts[2],re.M|re.S)
    if not section:return seal(result)
    statement=section.group(1).strip()
    # Entire section must be the unqualified dataset-wide grant. Extra caveats,
    # code-only statements, exclusions or multiple licenses do not match.
    match=re.fullmatch(r'The ([^\n]+) dataset is licensed under the \[MIT License\]\(https://opensource.org/licenses/MIT\)\.',statement)
    if source['license_id']!='MIT' or not match:return seal(result)
    name=match.group(1)
    if name not in (source['dataset_id'].split('/')[-1],data.get('pretty_name')) and name.casefold()!=source['dataset_id'].split('/')[-1].casefold():
        return seal(result)
    # Require a real dataset-creation narrative, not just the metadata flag.
    provenance=re.search(r'^#### Initial Data Collection and Normalization\s*\n(.*?)(?=^#{1,4} |\Z)',parts[2],re.M|re.S)
    if not provenance or len(provenance.group(1).strip())<80 or '[Needs More Information]' in provenance.group(1):
        return seal(dict(result,reason='dataset creation provenance missing'))
    if re.search(r'\b(derived|scraped|third.party|generated by|exceptions?|excluded|except)\b',provenance.group(1),re.I):
        return seal(dict(result,reason='dataset creation provenance requires scope review'))
    routes=[]
    configs=data.get('configs')
    if not isinstance(configs,list) or not configs:return seal(result)
    for config in configs:
        if not isinstance(config,dict) or not isinstance(config.get('config_name'),str) or not isinstance(config.get('data_files'),list):return seal(result)
        for f in config['data_files']:
            if not isinstance(f,dict) or set(f)!= {'path','split'} or not all(isinstance(f[k],str) for k in f):return seal(result)
            path=f['path']
            if path.startswith('/') or '\\' in path or '..' in PurePosixPath(path).parts or not re.fullmatch(r'[A-Za-z0-9_./*?-]+',path):return seal(result)
            routes.append(dict(config=config['config_name'],split=f['split'],path=path))
    if not routes:return seal(result)
    return seal(dict(result,status='COVERED',reason='explicit original-dataset license and configuration scope',
        routes=routes,license_statement=statement,provenance_statement=provenance.group(1).strip()))


def assess_provenance(text, source, receipt_identity):
    """Record publisher claims, never turn derivative claims into upstream grants.

    Links/creator narratives are leads, not verified copyright ownership. The
    supported positive proof remains the existing original-dataset scope profile.
    Synthetic/derivative inputs need a separately established rights chain; this
    assessment deliberately cannot infer that chain from an output license tag.
    """
    scope=scope_from_card(text,source,receipt_identity)
    parts=text.split('---',2)
    body=parts[2] if len(parts)==3 else text
    claims=sorted(set(line.strip() for line in body.splitlines() if re.search(
        r'\b(synthetic|generated|derived|extracted|scraped|upstream|seed|creators?|authors?)\b',line,re.I)))
    derivative=bool(re.search(r'\b(synthetic|generated by|derived|extracted from|scraped|seed samples|seed data)\b',body,re.I))
    links=sorted(set(re.findall(r'https://[^\s<>\)\]"\']+', '\n'.join(claims))))
    assessment=dict(version='publisher-provenance-assessment-v1',
        publisher_locator=source['locator'],dataset_id=source['dataset_id'],revision=source['revision'],
        card_identity=receipt_identity,declared_license=source['license_id'],
        publisher_claims=claims,referenced_evidence_locators=links,
        links_are_unverified_leads=True,derivative_or_synthetic_claims=derivative,
        creator_authority_verified=False,upstream_rights_verified=False,
        generated_record_coverage_verified=False)
    if derivative:
        scope=dict(scope,status='REVIEW',routes=[],reason='synthetic/derivative record coverage and upstream authority not proven')
        assessment['missing_evidence']=[
            'creator authority over the exact generated/derived records',
            'record-to-upstream input and generator/version provenance',
            'pinned upstream rights and applicable generation/output terms',
            'explicit license scope covering the selected payload records']
    else:
        assessment['missing_evidence']=[] if scope['status']=='COVERED' else ['supported explicit record rights scope']
    # A proven incompatible declaration can exclude, but an uncertain claim or
    # incidental mention of restrictive terms never establishes incompatibility.
    try:
        data=yaml.load(parts[1],Loader=UniqueLoader) if len(parts)==3 else None
    except (ValueError,yaml.YAMLError):data=None
    declared=data.get('license') if isinstance(data,dict) else None
    if isinstance(declared,list) and len(declared)==1:declared=declared[0]
    if not isinstance(declared,str) or declared.casefold() in ('','unknown','other','noassertion','none'):
        scope=dict(scope,status='REVIEW',routes=[],reason='missing/ambiguous license declaration')
    elif declared.casefold()==source['license_id'].casefold() and source['license_id'] not in LICENSES | CONDITIONAL.keys():
        scope=dict(scope,status='EXCLUDE',routes=[],reason='verified declaration outside existing license allowlist')
    return seal(dict(scope,provenance_assessment=assessment))


def resolve(document,scope):
    verify_seal(document);verify_seal(scope)
    need(document.get('policy')=='dataset-document-clearance-v1' and document['status'] in ('CLEAR','REVIEW','EXCLUDE'), 'Unsupported document proof')
    p=document['provenance']
    need(p['dataset_id']==scope['dataset_id'] and p['revision']==scope['revision'],'Rights scope dataset/revision mismatch')
    status,reason='REVIEW',scope['reason']
    if document['status']=='EXCLUDE':status,reason='EXCLUDE','preserved document exclusion: '+document['reason']
    elif scope['status']=='EXCLUDE':status='EXCLUDE'
    elif scope['status']=='COVERED':
        matches=[r for r in scope['routes'] if fnmatch.fnmatchcase(p['payload_path'],r['path'])]
        if not matches:status,reason='EXCLUDE','document outside explicit dataset file scope'
        elif len(matches)!=1 or matches[0]['split']!=p['upstream_split']:reason='ambiguous file/split scope'
        else:status,reason='CLEAR','verified record inherits explicit dataset license scope'
    return seal(dict(policy=VERSION,document_identity=document['document_identity'],source_id=document['source_id'],
        revision=document['revision'],path=document['path'],sha256=document['sha256'],provenance=p,
        scope_identity=scope['identity'],document_proof_identity=document['identity'],
        license_id=scope['license_id'] if status=='CLEAR' else None,status=status,reason=reason,
        training_allowed=False,production_admitted=False))


def build(documents,catalog,cards,cache,output,*,root=ROOT,resume=False,provenance_assessment=False):
    root=Path(root).resolve();documents=Path(documents).resolve();cards=Path(cards).resolve();cache=Path(cache).resolve();output=Path(output).resolve()
    need(output.is_relative_to(root) and all(not p.is_relative_to(output) and not output.is_relative_to(p) for p in (documents,cards,cache)), 'Output overlaps evidence/cache')
    reg=json.loads(Path(catalog).read_bytes());verify_seal(reg)
    receipt=json.loads((documents/'complete.json').read_bytes());verify_seal(receipt)
    need(file_digest(documents/'decisions.jsonl')==receipt['decisions_sha256'],'Document proof corrupt')
    request=json.loads((documents/'request.json').read_bytes());verify_seal(request)
    need(request.get('policy')=='dataset-document-clearance-v1','Unsupported document verification policy')
    need(request['identity']==receipt['request_identity'],'Document request mismatch')
    for name,digest in request['inputs'].items():need(file_digest(local_path(root,name))==digest,'Document proof input changed')
    need(request['inputs'].get(Path(catalog).resolve().relative_to(root).as_posix())==file_digest(catalog),'Catalog not bound to proof')
    sources={s['source_id']:s for s in reg['sources']};scopes={};hashes={}
    for sid,source in sources.items():
        path=cards/(sid+'.json');r=json.loads(path.read_bytes());verify_seal(r)
        need(r['dataset_id']==source['dataset_id'] and r['revision']==source['revision'],'Card pin mismatch')
        card=local_path(root,r['path']);data=card.read_bytes();entry=r['tree_entry']
        need(len(data)<=262144 and file_digest(card)==r['sha256'],'Card corrupt/oversized')
        need(r['url']==source['locator']+'/raw/'+source['revision']+'/README.md'
             and r['tree_url']==f"https://huggingface.co/api/datasets/{source['dataset_id']}/tree/{source['revision']}", 'Card origin mismatch')
        need(entry['path']=='README.md' and entry['type']=='file' and entry['size']==len(data)
             and entry['oid']==r['git_blob']==hashlib.sha1(f'blob {len(data)}\0'.encode()+data).hexdigest(),'Card Git binding mismatch')
        resolver=assess_provenance if provenance_assessment else scope_from_card
        scopes[sid]=resolver(data.decode('utf-8'),source,r['identity']);hashes[str(path.relative_to(root))]=file_digest(path)
    results=[];seen=set()
    # Verify actual cached bytes and whole pinned payload, rather than merely
    # trusting the prior document-decision file's seal.
    for sid,source in sources.items():
        directory=cache/sid;done=json.loads((directory/'complete.json').read_bytes());verify_seal(done)
        need(file_digest(directory/'inventory.jsonl')==done['inventory_sha256'],'Inventory changed')
        from training.production_acquisition import read_plan
        inventory={r['path']:r for r in read_plan(directory/'inventory.jsonl')}
        raw_sha=payload_digest(directory)
        for doc in read_plan(documents/'decisions.jsonl'):
            if doc['source_id']!=sid:continue
            need(doc['document_identity'] not in seen,'Duplicate document proof');seen.add(doc['document_identity'])
            r=inventory.get(doc['path']);need(r is not None and r['sha256']==doc['sha256'] and r['provenance']==doc['provenance'],'Document cache binding mismatch')
            need(file_digest(local_path(directory,r['local_blob']))==doc['sha256'] and raw_sha==doc['provenance']['payload_sha256'],'Document/payload changed')
            results.append(resolve(doc,scopes[sid]))
    need(len(results)==receipt['documents'],'Unmatched document proofs')
    request_data=dict(policy=VERSION,document_receipt=file_digest(documents/'complete.json'),catalog=file_digest(catalog),cards=hashes)
    if provenance_assessment:request_data['provenance_assessment']='publisher-provenance-assessment-v1'
    req=seal(request_data)
    output.mkdir(parents=True,exist_ok=True)
    if (output/'request.json').exists():need(resume and json.loads((output/'request.json').read_bytes())==req,'Resume evidence changed')
    else:need(not any(output.iterdir()),'Unknown output');atomic_json(output/'request.json',req)
    payload=b''.join(canonical(r)+b'\n' for r in sorted(results,key=lambda r:r['document_identity']))
    counts=Counter(r['status'] for r in results);per_source={s['dataset_id']:dict(Counter(r['status'] for r in results if r['source_id']==sid)) for sid,s in sources.items()}
    result=seal(dict(request_identity=req['identity'],counts={k:counts[k] for k in ('CLEAR','EXCLUDE','REVIEW')},per_source=per_source,
        documents=len(results),decisions_sha256='sha256:'+hashlib.sha256(payload).hexdigest(),scope_identities={k:v['identity'] for k,v in scopes.items()},production_admitted=0))
    if (output/'complete.json').exists():
        need(json.loads((output/'complete.json').read_bytes())==result and (output/'decisions.jsonl').read_bytes()==payload,'Replay mismatch')
        for sid,scope in scopes.items():need(json.loads((output/(sid+'-scope.json')).read_bytes())==scope,'Scope changed')
    else:
        for sid,scope in scopes.items():atomic_json(output/(sid+'-scope.json'),scope)
        temp=output/'decisions.part';temp.write_bytes(payload);atomic_replace(temp,output/'decisions.jsonl');atomic_json(output/'complete.json',result)
    return result


def main():
    p=argparse.ArgumentParser(description=__doc__)
    for k in ('documents','catalog','cards','cache','output'):p.add_argument('--'+k,type=Path,required=True)
    p.add_argument('--resume',action='store_true')
    p.add_argument('--provenance-assessment',action='store_true');a=p.parse_args()
    try:
        need(a.output.resolve().is_relative_to(ROOT/'artifacts'),'Output must stay under artifacts')
        with _writer_lock(a.output.with_name(a.output.name+'.scope')):result=build(**vars(a))
        print(json.dumps(result,sort_keys=True));return 0
    except Exception as exc:print(f'Rights scope stopped: {exc}');return 2


if __name__=='__main__':raise SystemExit(main())
